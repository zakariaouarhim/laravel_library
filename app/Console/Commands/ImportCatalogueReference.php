<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

/**
 * Load the reference catalogue (~81k books scraped from almouggar.com) into the
 * `catalogue_reference` table from a mysqldump. The dump itself carries
 * DROP TABLE IF EXISTS + CREATE TABLE + INSERTs, so the table's schema is defined
 * by the dump (single source of truth) and the import is fully idempotent — run
 * it again to refresh. The .sql lives under storage/app/catalogue_reference and
 * is git-ignored (uploaded to the VPS separately).
 *
 * WARNING: the drop/recreate also wipes the scraped rows that live in the same
 * table (dedup_key "bod:…", "lm:…", "ak:…") — re-run the matching scraper after
 * any re-import to restore them.
 *
 * `api:` rows are the exception: they are books an admin found through the
 * "find this book" search, so no command can regenerate them. They are copied
 * aside before the import and restored afterwards.
 */
class ImportCatalogueReference extends Command
{
    protected $signature = 'catalogue:import
        {--file= : Path to the mysqldump .sql (default: storage/app/catalogue_reference/catalogue_reference.sql)}';

    protected $description = 'Import the reference catalogue (used to enrich our books) from a mysqldump';

    public function handle(): int
    {
        $file = $this->option('file')
            ?: storage_path('app/catalogue_reference/catalogue_reference.sql');

        if (!is_file($file)) {
            $this->error("Dump not found: {$file}");
            return 1;
        }

        // Hold the admin-created `api:` rows in memory across the drop/recreate.
        // Everything else in this table can be regenerated by a scraper; these
        // cannot. Reviews key off catalogue_reference.id, so the ids are kept too.
        $preserved = DB::table('catalogue_reference')
            ->where('dedup_key', 'like', 'api:%')
            ->get()
            ->map(fn($r) => (array) $r)
            ->all();
        if ($preserved !== []) {
            $this->line('  holding ' . count($preserved) . ' api: row(s) aside across the rebuild');
        }

        $this->info('Importing catalogue reference from ' . basename($file) . ' ...');

        $handle = fopen($file, 'r');
        if (!$handle) {
            $this->error('Could not open the dump file.');
            return 1;
        }

        // mysqldump keeps every statement on complete lines (newlines inside
        // string literals are escaped), so accumulate lines until one ends with
        // ';' and run that statement. This avoids a single 57MB exec.
        $buffer     = '';
        $statements = 0;
        $inserts    = 0;

        // Foreign key checks off for a clean drop/recreate regardless of order.
        DB::statement('SET FOREIGN_KEY_CHECKS=0');

        try {
            while (($line = fgets($handle)) !== false) {
                $trimmed = rtrim($line);

                // Skip empty lines and standalone SQL comments.
                if ($trimmed === '' || str_starts_with(ltrim($trimmed), '--')) {
                    continue;
                }

                $buffer .= $line;

                if (substr($trimmed, -1) === ';') {
                    DB::unprepared($buffer);
                    $statements++;
                    if (stripos($buffer, 'INSERT INTO') !== false) {
                        $inserts++;
                        $this->output->write('.');
                    }
                    $buffer = '';
                }
            }
        } finally {
            fclose($handle);
            DB::statement('SET FOREIGN_KEY_CHECKS=1');
        }

        $this->newLine();

        // Put the admin's api: rows back. insertOrIgnore keyed on the original
        // id, so a dump that happens to reuse an id can't clobber a real row
        // (and the id is what catalogue_reviews points at).
        $restored = 0;
        foreach (array_chunk($preserved, 200) as $chunk) {
            $restored += DB::table('catalogue_reference')->insertOrIgnore($chunk);
        }
        if ($preserved !== []) {
            $this->info("Restored {$restored}/" . count($preserved) . ' api: row(s).');
            if ($restored < count($preserved)) {
                $this->warn('Some api: rows could not be restored (id collision with the dump) — check catalogue_reviews.');
            }
        }

        $count = DB::table('catalogue_reference')->count();
        $this->info("Done. {$statements} statements, {$inserts} INSERT batches → {$count} rows in catalogue_reference.");

        return 0;
    }
}
